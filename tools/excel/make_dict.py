def codes():
    """ROWS 순서대로 매긴 코드 (P-EV-001 …). 행을 끼워 넣으면 뒤 코드가 바뀌어요."""
    seq, out = {}, []
    for row in ROWS:
        k = JPFX[row[0]] + "-" + TPFX[row[4]]
        seq[k] = seq.get(k, 0) + 1
        out.append(f"{k}-{seq[k]:03d}")
    return out


def dict_records(targets=None, rows=None):
    """업무구분 시트 행 (화면 열 그대로). targets = {코드: {연도: 목표}}"""
    targets = targets or {}
    code_of = {id(r): c for r, c in zip(ROWS, codes())}
    out = []
    for row in (rows or ROWS):
        j, big, mid, name, typ, allow, loc, phys, ax, mode, defer, _two, desc = row
        code = code_of[id(row)]
        d = {"코드": code, "직군": j, "대분류": big, "중분류": mid, "소분류명": name, "TYPE": typ, "비가동 종류": allow or None,
             "수행 위치": loc or None, "라인 내 물리 업무": phys or None, "연기 가능": defer or None, "묶을 때 방식": mode or None,
             "설명": desc or None}
        for y, v in targets.get(code, {}).items():
            d[f"{y} 목표"] = v
        out.append(d)
    return out
